    // PARAMETERS
    // ============================================================

    real MAX_ERROR_PERCENT;
    real SUM_TOLERANCE;

    integer total_tests;
    integer passed_tests;
    integer failed_tests;


    // ============================================================
    // CLOCK / RESET / START
    // ============================================================

    reg clk;
    reg rst;
    reg start;


    // ============================================================
    // INPUTS
    // ============================================================

    reg [31:0] x0;
    reg [31:0] x1;
    reg [31:0] x2;
    reg [31:0] x3;


    // ============================================================
    // OUTPUTS
    // ============================================================

    wire [31:0] softmax0;
    wire [31:0] softmax1;
    wire [31:0] softmax2;
    wire [31:0] softmax3;

    wire done;


    // ============================================================
    // DUT
    // ============================================================

    softmax_base2 #(
        .N(4)
