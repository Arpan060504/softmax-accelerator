    // CLOCK
    // ============================================================

    always #5 clk = ~clk;


    // ============================================================
    // FP32 -> REAL
    // ============================================================

    function real fp32_to_real;

        input [31:0] value;

        reg        sign;
        reg [7:0]  exponent;
        reg [22:0] fraction;

        real mantissa;
        integer exp_unbiased;

        begin

            sign     = value[31];
            exponent = value[30:23];
            fraction = value[22:0];

            // Zero
            if (value[30:0] == 31'd0)
            begin
                fp32_to_real = 0.0;
            end

            // Infinity / NaN
            else if (exponent == 8'hFF)
            begin
                fp32_to_real = 0.0;
            end

            // Normal number
            else
            begin

                mantissa = 1.0 + (fraction / 8388608.0);

                exp_unbiased = exponent - 127;

                fp32_to_real =
                    mantissa * (2.0 ** exp_unbiased);

                if (sign)
                    fp32_to_real = -fp32_to_real;

            end

        end

    endfunction


    // ============================================================
    // ABS
    // ============================================================

    function real abs_real;

        input real value;

        begin
            if (value < 0.0)
                abs_real = -value;
            else
                abs_real = value;
        end

    endfunction


    // ============================================================
    // MAX
    // ============================================================

    function real max4;

        input real a;
        input real b;
        input real c;
        input real d;

        real m;

        begin

            m = a;

            if (b > m)
                m = b;

            if (c > m)
                m = c;

            if (d > m)
                m = d;

            max4 = m;

        end

    endfunction


    // ============================================================
    // CHECK ONE SOFTMAX OUTPUT
    // ============================================================

    task check_output;

        input integer index;
        input real expected;
        input [31:0] actual_bits;

        real actual;
        real error_percent;

        begin

            actual = fp32_to_real(actual_bits);

            if (expected == 0.0)
            begin

                if (actual == 0.0)
                    error_percent = 0.0;
                else
                    error_percent = 100.0;

            end

            else
            begin

                error_percent =
                    abs_real(actual - expected)
                    / abs_real(expected)
                    * 100.0;
            end


            if (error_percent <= MAX_ERROR_PERCENT)
            begin

                $display(
                    "       softmax%0d PASS | expected=%f actual=%f error=%f%%",
                    index,
                    expected,
                    actual,
                    error_percent
                );
            end

            else
            begin

                $display(
                    "       softmax%0d FAIL | expected=%f actual=%f error=%f%%",
                    index,
                    expected,
                    actual,
                    error_percent
                );

                failed_tests = failed_tests + 1;

            end

        end

    endtask


    // ============================================================
    // RUN ONE TEST
    // ============================================================

    task run_test;

        input integer test_number;

        input [31:0] in0;
        input [31:0] in1;
        input [31:0] in2;
        input [31:0] in3;

        real r0;
        real r1;
        real r2;
        real r3;

        real max_value;

        real e0;
        real e1;
        real e2;
        real e3;

        real denominator;

        real expected0;
        real expected1;
        real expected2;
        real expected3;

        real actual0;
        real actual1;
        real actual2;
        real actual3;

        real output_sum;

        integer cycles;
        integer local_failures;

        begin

            local_failures = 0;

            // ----------------------------------------------------
            // Convert input FP32 -> real
            // ----------------------------------------------------

            r0 = fp32_to_real(in0);
            r1 = fp32_to_real(in1);
            r2 = fp32_to_real(in2);
            r3 = fp32_to_real(in3);


            // ----------------------------------------------------
            // Reference softmax
            //
            // IMPORTANT:
            //
            // We subtract max exactly like the DUT's intended
            // softmax range reduction.
            // ----------------------------------------------------

            max_value = max4(r0, r1, r2, r3);

            e0 = $exp(r0 - max_value);
            e1 = $exp(r1 - max_value);
            e2 = $exp(r2 - max_value);
            e3 = $exp(r3 - max_value);

            denominator = e0 + e1 + e2 + e3;

            expected0 = e0 / denominator;
            expected1 = e1 / denominator;
            expected2 = e2 / denominator;
            expected3 = e3 / denominator;


            // ----------------------------------------------------
            // Apply inputs
            // ----------------------------------------------------

            @(negedge clk);

            x0 = in0;
            x1 = in1;
            x2 = in2;
            x3 = in3;

            start = 1'b1;

            @(negedge clk);

            start = 1'b0;


            // ----------------------------------------------------
            // Wait for DONE
            // ----------------------------------------------------

            cycles = 0;

            while (!done && cycles < 20)
            begin

                @(posedge clk);

                cycles = cycles + 1;

            end


            // ----------------------------------------------------
            // Timeout
            // ----------------------------------------------------

            if (!done)
            begin

                $display(
                    "TEST %0d FAIL: TIMEOUT waiting for done",
                    test_number
                );

                failed_tests = failed_tests + 1;

            end

            else
            begin

                // ------------------------------------------------
                // Read outputs
                // ------------------------------------------------

                actual0 = fp32_to_real(softmax0);
                actual1 = fp32_to_real(softmax1);
                actual2 = fp32_to_real(softmax2);
                actual3 = fp32_to_real(softmax3);

                output_sum =
                    actual0 +
                    actual1 +
                    actual2 +
                    actual3;


                // ------------------------------------------------
                // Display
                // ------------------------------------------------

                $display("");
                $display("================================================");
                $display("TEST %0d", test_number);
                $display("================================================");

                $display(
                    "INPUT : %f %f %f %f",
                    r0, r1, r2, r3
                );

                $display(
                    "REF   : %f %f %f %f",
                    expected0,
                    expected1,
                    expected2,
                    expected3
                );

                $display(
                    "DUT   : %f %f %f %f",
                    actual0,
                    actual1,
                    actual2,
                    actual3
                );

                $display(
                    "SUM   : %f",
                    output_sum
                );

                $display(
                    "DONE  : %b after %0d cycles",
                    done,
                    cycles
                );


                // ------------------------------------------------
                // Individual output checks
                // ------------------------------------------------

                check_output(
                    0,
                    expected0,
                    softmax0
                );

                check_output(
                    1,
                    expected1,
                    softmax1
                );

                check_output(
                    2,
                    expected2,
                    softmax2
                );

                check_output(
                    3,
                    expected3,
                    softmax3
                );


                // ------------------------------------------------
                // Sum check
                // ------------------------------------------------

                if (abs_real(output_sum - 1.0)
                    <= SUM_TOLERANCE)
                begin

                    $display(
                        "       SUM CHECK PASS | sum=%f",
                        output_sum
                    );

                end

                else
                begin

                    $display(
                        "       SUM CHECK FAIL | sum=%f",
                        output_sum
                    );

                    failed_tests = failed_tests + 1;

                end


                // ------------------------------------------------
                // Cycle check
                //
                // Expected:
                //
                // cycle 0 -> exp0
                // cycle 1 -> exp1
                // cycle 2 -> exp2
                // cycle 3 -> exp3
                //
                // Depending on start sampling, the observed
                // count can be 4 or 5 in this TB.
                // ------------------------------------------------

                if (cycles <= 6)
                begin

                    $display(
                        "       LATENCY CHECK PASS"
                    );

                end

                else
                begin

                    $display(
                        "       LATENCY CHECK FAIL"
                    );

                    failed_tests = failed_tests + 1;

                end

                total_tests = total_tests + 1;

            end

        end

    endtask


