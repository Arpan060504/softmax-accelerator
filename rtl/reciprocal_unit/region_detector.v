module region_detector (
    input  wire [31:0] x,
    output reg  [3:0]  region
);

    // ------------------------------------------------------------
    // 16 piecewise-linear regions
    //
    // Region 0  : [-4.0, -3.5)
    // Region 1  : [-3.5, -3.0)
    // Region 2  : [-3.0, -2.5)
    // Region 3  : [-2.5, -2.0)
    // Region 4  : [-2.0, -1.5)
    // Region 5  : [-1.5, -1.0)
    // Region 6  : [-1.0, -0.5)
    // Region 7  : [-0.5,  0.0)
    //
    // Region 8  : [ 0.0,  0.5)
    // Region 9  : [ 0.5,  1.0)
    // Region 10 : [ 1.0,  1.5)
    // Region 11 : [ 1.5,  2.0)
    // Region 12 : [ 2.0,  2.5)
    // Region 13 : [ 2.5,  3.0)
    // Region 14 : [ 3.0,  3.5)
    // Region 15 : [ 3.5,  4.0]
    //
    // x < -4  -> region 0  (clamped)
    // x >  4  -> region 15 (clamped)
    // ------------------------------------------------------------


    // ------------------------------------------------------------
    // IEEE-754 FP32 -> monotonically increasing unsigned value
    //
    // For positive numbers:
    //     ordered_x = x ^ 32'h80000000
    //
    // For negative numbers:
    //     ordered_x = ~x
    //
    // This allows ordinary unsigned comparison.
    // ------------------------------------------------------------

    reg [31:0] ordered_x;

    always @(*) begin

        if (x[31] == 1'b1)
            ordered_x = ~x;
        else
            ordered_x = x ^ 32'h80000000;

    end


    // ------------------------------------------------------------
    // Transformed FP32 boundaries
    // ------------------------------------------------------------

    // Negative boundaries
    localparam [31:0] B_NEG_3_5 = 32'h3F9FFFFF;
    localparam [31:0] B_NEG_3_0 = 32'h3FBFFFFF;
    localparam [31:0] B_NEG_2_5 = 32'h3FDFFFFF;
    localparam [31:0] B_NEG_2_0 = 32'h3FFFFFFF;
    localparam [31:0] B_NEG_1_5 = 32'h403FFFFF;
    localparam [31:0] B_NEG_1_0 = 32'h407FFFFF;
    localparam [31:0] B_NEG_0_5 = 32'h40FFFFFF;

    // Zero
    localparam [31:0] B_ZERO = 32'h80000000;

    // Positive boundaries
    localparam [31:0] B_POS_0_5 = 32'hBF000000;
    localparam [31:0] B_POS_1_0 = 32'hBF800000;
    localparam [31:0] B_POS_1_5 = 32'hBFC00000;
    localparam [31:0] B_POS_2_0 = 32'hC0000000;
    localparam [31:0] B_POS_2_5 = 32'hC0200000;
    localparam [31:0] B_POS_3_0 = 32'hC0400000;
    localparam [31:0] B_POS_3_5 = 32'hC0600000;


    // ------------------------------------------------------------
    // Region detection
    // ------------------------------------------------------------

    always @(*) begin

        // Default region
        region = 4'd0;

        // --------------------------------------------------------
        // [-4.0, -3.5)
        //
        // Anything below -4 is also clamped here.
        // --------------------------------------------------------

        if (ordered_x < B_NEG_3_5)
            region = 4'd0;


        // --------------------------------------------------------
        // [-3.5, -3.0)
        // --------------------------------------------------------

        else if (ordered_x < B_NEG_3_0)
            region = 4'd1;


        // --------------------------------------------------------
        // [-3.0, -2.5)
        // --------------------------------------------------------

        else if (ordered_x < B_NEG_2_5)
            region = 4'd2;


        // --------------------------------------------------------
        // [-2.5, -2.0)
        // --------------------------------------------------------

        else if (ordered_x < B_NEG_2_0)
            region = 4'd3;


        // --------------------------------------------------------
        // [-2.0, -1.5)
        // --------------------------------------------------------

        else if (ordered_x < B_NEG_1_5)
            region = 4'd4;


        // --------------------------------------------------------
        // [-1.5, -1.0)
        // --------------------------------------------------------

        else if (ordered_x < B_NEG_1_0)
            region = 4'd5;


        // --------------------------------------------------------
        // [-1.0, -0.5)
        // --------------------------------------------------------

        else if (ordered_x < B_NEG_0_5)
            region = 4'd6;


        // --------------------------------------------------------
        // [-0.5, 0.0)
        // --------------------------------------------------------

        else if (ordered_x < B_ZERO)
            region = 4'd7;


        // --------------------------------------------------------
        // [0.0, 0.5)
        // --------------------------------------------------------

        else if (ordered_x < B_POS_0_5)
            region = 4'd8;


        // --------------------------------------------------------
        // [0.5, 1.0)
        // --------------------------------------------------------

        else if (ordered_x < B_POS_1_0)
            region = 4'd9;


        // --------------------------------------------------------
        // [1.0, 1.5)
        // --------------------------------------------------------

        else if (ordered_x < B_POS_1_5)
            region = 4'd10;


        // --------------------------------------------------------
        // [1.5, 2.0)
        // --------------------------------------------------------

        else if (ordered_x < B_POS_2_0)
            region = 4'd11;


        // --------------------------------------------------------
        // [2.0, 2.5)
        // --------------------------------------------------------

        else if (ordered_x < B_POS_2_5)
            region = 4'd12;


        // --------------------------------------------------------
        // [2.5, 3.0)
        // --------------------------------------------------------

        else if (ordered_x < B_POS_3_0)
            region = 4'd13;


        // --------------------------------------------------------
        // [3.0, 3.5)
        // --------------------------------------------------------

        else if (ordered_x < B_POS_3_5)
            region = 4'd14;


        // --------------------------------------------------------
        // [3.5, 4.0]
        //
        // Anything above 4 is clamped here.
        // --------------------------------------------------------

        else
            region = 4'd15;

    end

endmodule